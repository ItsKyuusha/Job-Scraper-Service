// ─── Core Job Result Types ────────────────────────────────────────────────────

export type ScraperSource = "linkedin" | "jobstreet" | "glints" | "threads";

export type EmploymentType =
  | "full_time"
  | "part_time"
  | "contract"
  | "freelance"
  | "internship"
  | "unknown";

export type WorkplaceType = "onsite" | "remote" | "hybrid" | "unknown";

export interface JobResult {
  id: string;                        // UUID generated by scraper
  source: ScraperSource;
  title: string;
  company: string;
  location: string | null;
  description: string | null;
  employment_type: EmploymentType;
  workplace_type: WorkplaceType;
  salary_raw: string | null;         // e.g., "Rp 8.000.000 - Rp 12.000.000"
  salary_min: number | null;
  salary_max: number | null;
  currency: string;                  // "IDR" default
  source_url: string;
  posted_at: string | null;          // ISO string or raw text
  scraped_at: string;                // ISO string
}

// ─── Scraper Input (Query Parameters) ────────────────────────────────────────

export interface ScrapeQuery {
  keyword: string;          // job title/role to search
  location?: string;        // e.g., "Jakarta", "Remote"
  page?: number;            // pagination (default: 1)
  limit?: number;           // max results to return (default: 20)
}

// ─── Scraper Interface (Abstract Base) ───────────────────────────────────────

export interface IScraper {
  source: ScraperSource;
  scrape(query: ScrapeQuery): Promise<JobResult[]>;
}

// ─── API Response Wrappers ────────────────────────────────────────────────────

export interface ScrapeSuccessResponse {
  success: true;
  source: ScraperSource | "multi";
  query: ScrapeQuery;
  total: number;
  results: JobResult[];
  scraped_at: string;
  duration_ms: number;
}

export interface ScrapeErrorResponse {
  success: false;
  source: ScraperSource | "multi";
  error: string;
  detail?: string;
}

export type ScrapeResponse = ScrapeSuccessResponse | ScrapeErrorResponse;

// ─── Job Queue Types ─────────────────────────────────────────────────────────

export type JobStatus = "queued" | "running" | "done" | "failed";

export interface QueuedJob {
  id: string;
  sources: ScraperSource[];
  query: ScrapeQuery;
  status: JobStatus;
  created_at: string;
  started_at?: string;
  finished_at?: string;
  result?: JobResult[];
  error?: string;
}
